#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_kpi_answers_all_four_questions() {
        for kind in KpiKind::ALL {
            let explanation = for_kpi(kind);
            for text in [
                explanation.what,
                explanation.how,
                explanation.why,
                explanation.missing,
            ] {
                assert!(!text.trim().is_empty(), "{kind:?} left a question blank");
            }
        }
    }

    #[test]
    fn no_explanation_asserts_a_benchmark_figure() {
        // A benchmark would read as a bare unit-carrying number the owner did
        // not set. The only numerals allowed are the ones that describe the
        // instrument itself: the twelve questions, their one-to-five scale, the
        // six dimensions, and the worked ROI illustration.
        let allowed = ["12", "1", "5", "6", "119", "3.0", "2"];
        for kind in KpiKind::ALL {
            let explanation = for_kpi(kind);
            for text in [explanation.what, explanation.how, explanation.why] {
                for word in text.split_whitespace() {
                    let trimmed = word.trim_matches(|c: char| !c.is_ascii_digit());
                    if !trimmed.is_empty() {
                        assert!(
                            allowed.contains(&trimmed),
                            "{kind:?} names the figure {trimmed}, which reads as a benchmark"
                        );
                    }
                }
            }
        }
    }
}
